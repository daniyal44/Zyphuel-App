    fun getSupportedLanguages(): List<AppLanguage> = supportedLanguages

    fun getPopularLanguages(): List<AppLanguage> = listOf(
        getLanguageByCode("en"),
        getLanguageByCode("ur"),
        getLanguageByCode("pa"),
        getLanguageByCode("ar"),
        getLanguageByCode("zh"),
