    fun translate(key: String, langCode: String, fallback: String): String {
        val entry = translations[key] ?: return fallback
        val normalized = langCode.lowercase()
        entry[normalized]?.let { return it }
        val parentCode = languageFallbackParent[normalized]
        if (parentCode != null) {
            entry[parentCode]?.let { return it }
        }
        return entry["en"] ?: fallback
    }
